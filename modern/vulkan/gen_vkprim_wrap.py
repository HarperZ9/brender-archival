"""Write vkprim_wrap.c: a primitive library and a primitive state that pass
every method through to an inner object (softprim's), except the ones vkprim
replaces, which vkprim.c defines.

    python modern/vulkan/gen_vkprim_wrap.py <dev_objs.cgh> > modern/vulkan/vkprim_wrap.c

dev_objs.cgh is generated by BRender 1.4's build (core/fw, classgen.pl) and
lists every method of every DDI class in order. The output is committed;
rerun this when the BlazingRenderer pin changes. Standard library only.
"""
from __future__ import annotations

import re
import sys

OVERRIDE = {
    "br_primitive_library_dispatch": {"stateNew", "flush"},
    "br_primitive_state_dispatch": {"renderBegin", "renderEnd", "stateCopy"},
}
PREFIX = {"br_primitive_library_dispatch": "vkp_plib", "br_primitive_state_dispatch": "vkp_state"}
WRAPPER = {"br_primitive_library_dispatch": "vkp_library", "br_primitive_state_dispatch": "vkp_pstate"}

ENTRY = re.compile(r"\t(.+?) BR_CMETHOD_PTR_DECL\((\w+), (\w+)\)\((.*?)\);", re.S)


def methods(text: str, dispatch: str):
    start = text.index(f"struct  {dispatch} {{")
    body = text[start:text.index("\n};", start)]
    for ret, cls, name, params in ENTRY.findall(body):
        # dev_objs.cgh spells some types "class" under a #define it undoes
        params = [re.sub(r"\bclass\b", "struct", p.strip()) for p in params.replace("\n", " ").split(",")]
        yield re.sub(r"\bclass\b", "struct", ret.strip()), cls, name, params


def arg_name(param: str) -> str:
    return re.findall(r"\w+", param)[-1]


def emit(text: str, dispatch: str) -> list[str]:
    out, table = [], []
    prefix, wrapper = PREFIX[dispatch], WRAPPER[dispatch]
    for ret, cls, name, params in methods(text, dispatch):
        if name.startswith("_reserved"):
            table.append(f"    .__{name[1:]} = NULL,")
            continue
        table.append(f"    ._{name} = BR_CMETHOD_REF({prefix}, {name}),")
        if name in OVERRIDE[dispatch]:
            out.append(f"{ret} BR_CMETHOD_DECL({prefix}, {name})({', '.join(params)});")
            continue
        self_type = params[0].rsplit("*", 1)[0].strip() + " *"
        args = ", ".join([f"({self_type})(({wrapper} *)self)->inner"] + [arg_name(p) for p in params[1:]])
        call = f"(({wrapper} *)self)->inner->dispatch->_{name}({args})"
        out.append(f"static {ret} BR_CMETHOD_DECL({prefix}, {name})({', '.join(params)})")
        out.append("{")
        out.append(f"    {'' if ret == 'void' else 'return '}{call};")
        out.append("}")
        out.append("")
    out.append(f"const struct {dispatch} {prefix}_dispatch = {{")
    out.extend(table)
    out.append("};")
    out.append("")
    return out


def main(argv: list[str]) -> int:
    text = open(argv[1], encoding="utf-8").read()
    lines = ["/*", " * SPDX-License-Identifier: MIT",
             " * Generated by gen_vkprim_wrap.py from BRender 1.4's dev_objs.cgh: pass-through",
             " * methods for vkprim's primitive library and primitive state. Do not edit;",
             " * the methods vkprim replaces are defined in vkprim.c.", " */",
             '#include "vkprim_ip.h"', ""]
    for dispatch in ("br_primitive_library_dispatch", "br_primitive_state_dispatch"):
        lines += emit(text, dispatch)
    sys.stdout.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
